<?php

namespace App\Support;

use Carbon\Carbon;

/**
 * Easter-based moving holidays (Gregorian calendar).
 *
 * Uses the anonymous Gregorian algorithm (Meeus/Jones/Butcher), so it does
 * not depend on PHP's optional "calendar" extension.
 */
final class Easter
{
    public static function sunday(int $year): Carbon
    {
        $a = $year % 19;
        $b = intdiv($year, 100);
        $c = $year % 100;
        $d = intdiv($b, 4);
        $e = $b % 4;
        $f = intdiv($b + 8, 25);
        $g = intdiv($b - $f + 1, 3);
        $h = (19 * $a + $b - $d - $g + 15) % 30;
        $i = intdiv($c, 4);
        $k = $c % 4;
        $l = (32 + 2 * $e + 2 * $i - $h - $k) % 7;
        $m = intdiv($a + 11 * $h + 22 * $l, 451);
        $month = intdiv($h + $l - 7 * $m + 114, 31);
        $day = (($h + $l - 7 * $m + 114) % 31) + 1;

        return Carbon::create($year, $month, $day)->startOfDay();
    }

    public static function goodFriday(int $year): Carbon
    {
        return self::sunday($year)->subDays(2);
    }
}
